// Tagged Word templates (ART-024, ART-025, ART-028, ART-029). Organisations adapt their own Word
// templates by typing tags where generated content goes:
//
//   {{field}}                      a merge field, such as {{initiative.name}} or {{document.version}}
//   {{content}}                    the artefact's standard content (every section), alone in its paragraph
//   {{section:<id>}}               one standard section, such as {{section:executiveSummary}}
//   {{narrative:<key>}}            a narrative written in the application, such as {{narrative:decisionsRequired}}
//   {{chart:<id>}}                 a chart or heatmap, such as {{chart:impactHeatmap}}
//   {{toc}}                        a table of contents
//   {{groups.name}} {{groups.headcount}} …  in one table row: the row repeats for each impacted group
//   {{#each groups}} … {{item.name}} … {{/each}}   repeating paragraphs and tables, one copy per item
//   {{#if plan.resistance}} … {{/if}}              included only when the condition holds ({{#if !…}} negates)
//
// Block tags (#each, #if, /each, /if, content, section, narrative, chart and toc) must be alone in their
// paragraph. Unknown tags are reported when the template is uploaded and shown as visible markers if
// generated, so a gap is never silent.
