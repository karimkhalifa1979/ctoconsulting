const plainText = (v) => String(v ?? '').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();

// --- Template XML handling ------------------------------------------------------------------------------
const TAG = /\{\{\s*([^{}]+?)\s*\}\}/g;

// End index of the element starting at i (tag such as w:p), allowing for nested elements of the same name.
function elementEnd(s, i, tag) {
  const open = s.indexOf('>', i);
  if (s[open - 1] === '/') return open + 1;
  const re = new RegExp(`<(/?)${tag}(?=[\\s>/])[^>]*?(/?)>`, 'g');
  re.lastIndex = open + 1;
  let depth = 1;
  let m;
  while ((m = re.exec(s))) {
    if (m[1] === '/') depth--;
    else if (m[2] !== '/') depth++;
    if (depth === 0) return re.lastIndex;
  }
  return s.length;
}

function topLevel(inner) {
  const out = [];
  let i = 0;
  while (i < inner.length) {
    const lt = inner.indexOf('<', i);
    if (lt < 0) { if (inner.slice(i).trim()) out.push(inner.slice(i)); break; }
    if (lt > i && inner.slice(i, lt).trim()) out.push(inner.slice(i, lt));
    const m = /^<([A-Za-z0-9:]+)/.exec(inner.slice(lt, lt + 60));
    if (!m) { out.push(inner.slice(lt)); break; }
    const end = elementEnd(inner, lt, m[1]);
    out.push(inner.slice(lt, end));
    i = end;
  }
  return out;
}

export const paragraphText = (p) => [...p.matchAll(/<w:t(?:\s[^>]*)?>([^<]*)<\/w:t>/g)].map((x) => x[1]).join('').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&apos;/g, "'");

// Paragraphs whose tags are split across runs (as Word often stores them) are rewritten as a single run
// in the first run's formatting, so every tag can be found and replaced.
function normaliseParagraphs(xml) {
  let out = '';
  let i = 0;
  const re = /<w:p(?=[\s>])/g;
  let m;
  while ((m = re.exec(xml))) {
    const start = m.index;
    const end = elementEnd(xml, start, 'w:p');
    const p = xml.slice(start, end);
    out += xml.slice(i, start);
    const text = paragraphText(p);
    if (!text.includes('{{') || /<w:(drawing|pict|object|fldChar|instrText)[\s>]/.test(p) || /<w:p[\s>]/.test(p.slice(4))) out += p;
    else {
      const pPr = /<w:pPr>[\s\S]*?<\/w:pPr>/.exec(p)?.[0] || '';
      const rPr = /<w:r(?:\s[^>]*)?>\s*(<w:rPr>[\s\S]*?<\/w:rPr>)/.exec(p)?.[1] || '';
      const openTag = /^<w:p(?:\s[^>]*)?>/.exec(p)[0];
      out += `${openTag}${pPr}<w:r>${rPr}<w:t xml:space="preserve">${escapeXml(text)}</w:t></w:r></w:p>`;
    }
    i = end;
    re.lastIndex = end;
  }
  return out + xml.slice(i);
}

const blockTag = (el) => {
  if (!el.startsWith('<w:p')) return null;
  const t = paragraphText(el).trim();
  const m = /^\{\{\s*([#/])\s*(if|each)\s*([^}]*)\}\}$/.exec(t);
  return m ? { open: m[1] === '#', kind: m[2], expr: m[3].trim() } : null;
};

function expand(elements, data, problems, prefix = '') {
  const out = [];
  for (let i = 0; i < elements.length; i++) {
    const tag = blockTag(elements[i]);
    if (!tag) { out.push(elements[i]); continue; }
    if (!tag.open) { problems.push(`{{/${tag.kind}}} without a matching {{#${tag.kind}}}.`); continue; }
    let depth = 1;
    let j = i + 1;
    for (; j < elements.length; j++) {
      const t = blockTag(elements[j]);
      if (t?.kind === tag.kind) depth += t.open ? 1 : -1;
      if (depth === 0) break;
    }
    if (depth !== 0) { problems.push(`{{#${tag.kind} ${tag.expr}}} is not closed with {{/${tag.kind}}}.`); continue; }
    const inner = elements.slice(i + 1, j);
    if (tag.kind === 'if') {
      const neg = tag.expr.startsWith('!');
      const key = tag.expr.replace(/^!/, '').trim();
      if (!(key in data.conditions)) problems.push(`Unknown condition "${key}".`);
      if (!!data.conditions[key] !== neg) out.push(...expand(inner, data, problems, prefix));
    } else {
      const items = data.collections[tag.expr];
      if (!items) problems.push(`Unknown collection "${tag.expr}".`);
      (items || []).forEach((_, n) => {
        const copy = inner.map((el) => el.replace(/\{\{\s*item\./g, `{{each.${tag.expr}.${n}.`));
        out.push(...expand(copy, data, problems, prefix));
      });
    }
    i = j;
  }
  return out;
}

// Rewrites a template's document part: normalised tags, then repeating and conditional sections expanded.
export function preprocessDocumentXml(xml, data, problems = []) {
  const norm = normaliseParagraphs(xml);
  const bodyStart = norm.indexOf('<w:body>');
  const bodyEnd = norm.lastIndexOf('</w:body>');
  if (bodyStart < 0 || bodyEnd < 0) return norm;
  const inner = norm.slice(bodyStart + 8, bodyEnd);
  const sectAt = inner.lastIndexOf('<w:sectPr');
  const content = sectAt >= 0 ? inner.slice(0, sectAt) : inner;
  const sect = sectAt >= 0 ? inner.slice(sectAt) : '';
  return `${norm.slice(0, bodyStart + 8)}${expand(topLevel(content), data, problems).join('')}${sect}${norm.slice(bodyEnd)}`;
}
export const preprocessPartXml = (xml) => normaliseParagraphs(xml);

// Classifies a tag: a known merge field, a block, a table-row field, a section marker or unknown.
export function classifyTag(tag, catalogue = fieldCatalogue()) {
  const t = tag.trim();
  if (/^[#/]\s*(if|each)\b/.test(t)) return { kind: 'structure' };
  if (t === 'content' || t === 'toc') return { kind: 'block', block: t };
  const b = /^(section|narrative|chart):(\w+)$/.exec(t);
  if (b) return BLOCK_IDS[b[1]].includes(b[2]) ? { kind: 'block', block: b[1], id: b[2] } : { kind: 'unknown', reason: `Unknown ${b[1]} "${b[2]}"` };
  if (catalogue.fields.some((f) => f.field === t)) return { kind: 'field' };
  const each = /^each\.(\w+)\.(\d+)\.(\w+)$/.exec(t);
  if (each) return { kind: 'eachField', collection: each[1], index: Number(each[2]), field: each[3] };
  const item = /^item\.(\w+)$/.exec(t);
  if (item) return { kind: 'itemField', field: item[1] };
  const row = /^(\w+)\.(\w+)$/.exec(t);
  if (row && COLLECTIONS[row[1]]) return COLLECTIONS[row[1]].fields.some(([k]) => k === row[2]) ? { kind: 'rowField', collection: row[1], field: row[2] } : { kind: 'unknown', reason: `"${row[2]}" is not a field of ${row[1]}` };
  return { kind: 'unknown', reason: 'Not in the field catalogue' };
}

// ART-028: validation on upload, reporting unknown merge fields and structural errors.
export async function validateDocxTemplate(bytes) {
  const { default: JSZip } = await import('jszip');
  let zip;
  try { zip = await JSZip.loadAsync(bytes); } catch { return { ok: false, errors: ['The file is not a valid Word document (.docx).'], warnings: [], tags: [], unknown: [] }; }
  if (!zip.file('word/document.xml')) return { ok: false, errors: ['The file has no document part; it is not a Word document.'], warnings: [], tags: [], unknown: [] };
  const catalogue = fieldCatalogue();
  const errors = [];
  const warnings = [];
  const tags = new Map();
  const parts = Object.keys(zip.files).filter((f) => /^word\/(document|header\d*|footer\d*)\.xml$/.test(f));
  let hasContent = false;
  for (const part of parts) {
    const xml = normaliseParagraphs(await zip.file(part).async('string'));
    const stack = [];
    const re = /<w:p(?=[\s>])/g;
    let m;
    while ((m = re.exec(xml))) {
      const end = elementEnd(xml, m.index, 'w:p');
      const ptext = paragraphText(xml.slice(m.index, end));
      re.lastIndex = end;
      for (const tm of ptext.matchAll(TAG)) {
        const t = tm[1].trim();
        const c = classifyTag(t, catalogue);
        const e = tags.get(t) || { tag: t, kind: c.kind, parts: new Set(), count: 0 };
        e.parts.add(part.replace('word/', ''));
        e.count++;
        tags.set(t, e);
        if (c.kind === 'unknown') errors.push(`{{${t}}} in ${part.replace('word/', '')}: ${c.reason}.`);
        if ((c.kind === 'block' || c.kind === 'structure') && ptext.trim() !== tm[0]) warnings.push(`{{${t}}} should be alone in its paragraph; the rest of the paragraph will be lost.`);
        if (c.kind === 'block' && part !== 'word/document.xml') errors.push(`{{${t}}} can only be used in the body, not in ${part.replace('word/', '')}.`);
        if (c.kind === 'block' && c.block === 'content') hasContent = true;
        if (c.kind === 'structure') {
          const s = /^([#/])\s*(if|each)\s*(.*)$/.exec(t);
          if (s[1] === '#') {
            stack.push(s[2]);
            if (s[2] === 'each' && !COLLECTIONS[s[3].trim()]) errors.push(`{{${t}}}: unknown collection "${s[3].trim()}".`);
            if (s[2] === 'if' && !catalogue.conditions.some((x) => x.tag === s[3].replace(/^!/, '').trim())) errors.push(`{{${t}}}: unknown condition "${s[3].replace(/^!/, '').trim()}".`);
          } else if (stack.pop() !== s[2]) errors.push(`{{${t}}} does not match the section it closes.`);
        }
      }
    }
    if (stack.length) errors.push(`${stack.length} {{#${stack[stack.length - 1]}}} section(s) in ${part.replace('word/', '')} are not closed.`);
  }
  const list = [...tags.values()].map((x) => ({ ...x, parts: [...x.parts] }));
  if (!hasContent && !list.some((x) => x.kind === 'block')) warnings.push('The template has no {{content}} or {{section:…}} tag, so only merge fields will be filled in.');
  if (list.some((x) => x.kind === 'itemField') && !list.some((x) => x.tag.startsWith('#each'))) errors.push('{{item.…}} fields are only valid inside {{#each …}} sections.');
  return { ok: errors.length === 0, errors: [...new Set(errors)], warnings: [...new Set(warnings)], tags: list, unknown: list.filter((x) => x.kind === 'unknown').map((x) => x.tag), checkedAt: new Date().toISOString() };
}

