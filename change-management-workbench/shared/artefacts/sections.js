export function readinessByGroupChart(s) {
  const gs = s.groups.filter((g) => g.readiness.index != null);
  if (!gs.length) return p('No readiness index can be calculated yet.');
  return chart('bar', { title: 'Readiness index by impacted group', categories: gs.map((g) => g.name), series: [{ name: 'Readiness index', values: gs.map((g) => g.readiness.index) }], max: 100, min: 0, threshold: { value: s.settings.readinessThreshold, label: 'Threshold' }, height: Math.max(200, gs.length * 30 + 60) });
}
// Readiness over time: each group's average ADKAR score at each assessment.
export function readinessTrendChart(s) {
  const dates = uniq(s.groups.flatMap((g) => g.adkarHistory.map((r) => r.date))).filter(Boolean).sort();
  const gs = s.groups.filter((g) => g.adkarHistory.length > 1);
  if (dates.length < 2 || !gs.length) return p('Readiness trends appear once groups have been assessed more than once.', 'small');
  const avg = (r) => { const v = ADKAR_IDS.map((el) => r.scores?.[el]).filter((y) => y != null); return v.length ? Math.round((v.reduce((a, b) => a + b, 0) / v.length) * 100) / 100 : null; };
  return chart('line', {
    title: 'Readiness trend: average ADKAR score by group', categories: dates.map((d) => fmtDate(d)),
    series: gs.map((g, i) => ({ name: g.name, values: dates.map((d) => { const r = g.adkarHistory.find((y) => y.date === d); return r ? avg(r) : null; }), color: SERIES[i % SERIES.length] })),
    min: 1, max: 5, threshold: { value: s.settings.adkarThreshold, label: 'Barrier threshold' }, height: 280,
  });
}

