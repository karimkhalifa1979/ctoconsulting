// --- 13 Integrated timeline ------------------------------------------------------------------------
export function timelineTable(s, x, { list, caption = 'Integrated timeline: change activities against releases and milestones', limit = 45 } = {}) {
  const items = (list || x.acts(() => true)).filter((a) => a.start).slice(0, limit);
  const dates = [...items.flatMap((a) => [a.start, a.end]), ...s.milestones.map((m) => m.date)].filter(Boolean).sort();
  if (!dates.length) return p('Nothing is scheduled yet.');
  let start = dates[0] < addMonths(s.today, -4) ? addMonths(s.today, -4) : dates[0];
  let end = dates[dates.length - 1];
  if (end > addMonths(start, 13)) end = addMonths(start, 13);
  const periods = periodRange(start, end, 'month');
  const planColour = Object.fromEntries(s.plans.map((pl, i) => [pl.id, SERIES[i % SERIES.length]]));
  const rows = [
    ...s.milestones.filter((m) => m.date >= periods[0].start && m.date <= periods[periods.length - 1].end).map((m) => [{ text: `Milestone: ${m.name}`, bold: true }, '', fmtDate(m.date), ...periods.map((pr) => (monthKey(m.date) === pr.key ? { text: '◆', align: 'c', color: '0B1F3A', bold: true } : ''))]),
    ...items.map((a) => [a.title, x.planName(a.plans[0]), x.when(a), ...periods.map((pr) => ((a.start || '') <= pr.end && (a.end || a.start || '') >= pr.start ? { text: '', fill: planColour[a.plans[0]] || SERIES[0] } : ''))]),
  ];
  return table([{ label: 'Activity or milestone', w: 4 }, { label: 'Plan', w: 1.8 }, { label: 'Dates', w: 2 }, ...periods.map((pr) => ({ label: shortMonth(pr.start), w: 0.55, align: 'c' }))], rows,
    { caption, small: true, note: `${items.length < (list || s.activities).length ? `First ${items.length} scheduled activities shown; the appendix lists every activity. ` : ''}Shaded months show when each activity runs; ◆ marks a milestone.` });
}
