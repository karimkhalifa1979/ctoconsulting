export function impactHeatmapTable(s, { L, caption = 'Impact heatmap: degree of impact by group and aspect' } = {}) {
  const aspects = Object.keys(s.lists.impactAspect || {}).filter((a) => s.groups.some((g) => g.degrees?.[a] != null));
  return table([{ label: 'Impacted group', w: 3 }, ...aspects.map((a) => ({ label: L('impactAspect', a), w: 1, align: 'c', vertical: true })), { label: 'Overall', w: 1, align: 'c', vertical: true }],
    s.groups.map((g) => [g.name, ...aspects.map((a) => heat(g.degrees?.[a])), { ...heat(g.overall), bold: true }]),
    { caption, small: true, empty: 'No impacted groups recorded.', note: 'Degree of impact from 0 (none) to 5 (very high). Darker cells are more highly impacted.' });
}
const heat = (d) => (d == null ? { text: '—' } : { text: String(d), fill: impactFill(d), color: impactInk(d), align: 'c' });

export function impactTimelineTable(s, { months } = {}) {
  const start = s.initiative.startDate && s.initiative.startDate > addMonths(s.today, -6) ? s.initiative.startDate : addMonths(s.today, -2);
  const end = s.initiative.endDate && s.initiative.endDate < addMonths(start, 18) ? s.initiative.endDate : addMonths(start, 14);
  const periods = (months || periodRange(start, end, 'month')).slice(0, 15);
  const window = (x) => {
    const st = x.feltFrom || x.milestoneDate;
    if (!st) return null;
    const en = x.feltTo || (x.transitionWeeks ? addMonths(st, Math.ceil(Number(x.transitionWeeks) / 4.3)) : addMonths(st, 2));
    return [st, en];
  };
  const rows = s.groups.map((g) => {
    const xs = s.impacts.filter((x) => x.groupId === g.id).map((x) => ({ x, w: window(x) })).filter((y) => y.w);
    return [g.name, ...periods.map((pr) => {
      const on = xs.filter(({ w }) => w[0] <= pr.end && w[1] >= pr.start);
      if (!on.length) return { text: '' };
      const max = Math.max(...on.map(({ x }) => x.degree || 0));
      return { text: on.length > 1 ? `${max}·${on.length}` : String(max), fill: impactFill(max), color: impactInk(max), align: 'c' };
    })];
  });
  return table([{ label: 'Impacted group', w: 3 }, ...periods.map((pr) => ({ label: shortMonth(pr.start), w: 0.8, align: 'c' }))], rows,
    { caption: 'Impact timeline: highest degree of impact felt by each group by month', small: true, note: 'Cells show the highest degree of impact felt in the month, then the number of concurrent impacts where there is more than one.' });
}
export const shortMonth = (iso) => { const d = new Date(`${String(iso).slice(0, 10)}T00:00:00Z`); return `${d.toLocaleDateString('en-AU', { month: 'short', timeZone: 'UTC' })} ${String(d.getUTCFullYear()).slice(2)}`; };

