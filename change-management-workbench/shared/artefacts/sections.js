// --- 2 Executive summary ------------------------------------------------------------------------------
export function executiveSummary(s, x) {
  const { narrative } = x;
  const n = narrative('executiveSummary');
  const ms = s.milestones.filter((m) => ['release', 'goLive', 'wave', 'hypercareExit'].includes(m.kind)).slice(0, 6);
  const topRisks = sortBy(s.risks.filter((r) => r.status !== 'closed'), (r) => RATING_ORDER.indexOf(r.rating)).slice(0, 3);
  const plans = s.plans.filter((pl) => pl.selected);
  const dec = narrative('decisionsRequired');
  return {
    id: 'executiveSummary', title: 'Executive summary',
    blocks: [
      ...(n ? rich(n.html, { aiDrafted: n.aiDrafted }) : [p(`${s.initiative.name} changes how ${fmtNum(s.kpis.headcount)} people across ${s.groups.length} impacted groups work. ${s.kpis.highImpactGroups} groups are highly impacted. The overall change risk profile is ${s.risk.profile || 'not yet assessed'}.`)]),
      kv([
        ['Purpose', truncate(text(s.initiative.reasonForChange || s.initiative.description), 400)],
        ['Objectives', s.objectives.map((o) => o.title).join('; ')],
        ['Key dates', ms.map((m) => `${m.name} (${fmtDate(m.date)})`).join('; ')],
        ['Risk profile', s.risk.profile ? `${cap(s.risk.profile)} risk (change characteristics ${s.risk.ccScore ?? '—'}, organisational attributes ${s.risk.oaScore ?? '—'})` : 'Not yet assessed'],
        ['Plan overview', `${plans.map((pl) => pl.label).join(', ')}. ${s.kpis.activitiesComplete} of ${s.kpis.activitiesTotal} activities complete.`],
        ['Top risks', topRisks.map((r) => `${r.title} (${r.rating})`).join('; ') || 'None open'],
        ['Decisions required', dec ? truncate(text(dec.html), 400) : 'None recorded'],
      ], { caption: 'Change on a page' }),
      ...(s.aiUnreviewed ? [callout('warn', 'AI-drafted content', 'Parts of this document were drafted with AI assistance and have not yet been reviewed and accepted. They are marked where they appear.')] : []),
    ],
  };
}

