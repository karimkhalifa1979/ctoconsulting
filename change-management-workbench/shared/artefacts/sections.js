export function helpers(s) {
  const L = labeller(s);
  const groupName = (id) => s.groups.find((g) => g.id === id)?.name || '';
  const planName = (id) => s.plans.find((x) => x.id === id)?.label || id;
  const selected = (id) => s.initiative.selectedPlans.includes(id);
  const acts = (fn) => sortBy(s.activities.filter((a) => a.status !== 'cancelled' && fn(a)), (a) => a.start || '9999', 'code');
  const statusCell = (a) => (a.overdue ? { text: 'Overdue', fill: STATUS.criticalSoft, color: STATUS.criticalInk, bold: true } : L('activityStatus', a.status));
  const when = (a) => (a.start && a.end && a.end !== a.start ? `${fmtDate(a.start)} – ${fmtDate(a.end)}` : fmtDate(a.start) || 'To be scheduled');
  const narrative = (key) => s.narratives?.[key];
  return { L, groupName, planName, selected, acts, statusCell, when, narrative };
}

const text = (v) => plain(v);
const para = (v, fallback) => (plain(v) ? rich(v) : fallback ? [placeholder(fallback)] : []);

