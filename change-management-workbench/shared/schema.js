export const ENTITY_TYPES = Object.keys(ENTITIES);

// Types whose records belong to an initiative.
export const INITIATIVE_TYPES = ENTITY_TYPES.filter((t) => ENTITIES[t].scope === 'initiative');

export function entity(type) {
  const e = ENTITIES[type];
  if (!e) throw new Error(`Unknown record type: ${type}`);
  return e;
}

// Schema for a type including administrator-defined custom fields (ADM-002) and terminology (ADM-003).
export function fieldsOf(type, config = {}) {
  const base = entity(type).fields;
  const custom = (config.customFields?.[type] || []).map((cf) => ({ ...cf, key: cf.key.startsWith('cf_') ? cf.key : `cf_${cf.key}`, custom: true }));
  const sens = config.settings?.sensitiveFields?.[type];
  const terms = config.settings?.terminology || {};
  return [...base, ...custom].map((fd) => ({
    ...fd,
    label: terms[`${type}.${fd.key}`] || fd.label,
    sensitive: sens ? sens.includes(fd.key) || (fd.custom && fd.sensitive) : !!fd.sensitive,
  }));
}

export function fieldOf(type, key, config) {
  return fieldsOf(type, config).find((x) => x.key === key);
}

export function sensitiveKeys(type, config) {
  return fieldsOf(type, config).filter((x) => x.sensitive).map((x) => x.key);
}

export function listOptions(listName, config) {
  return config?.lists?.[listName] || DEFAULT_LISTS[listName] || [];
}

export function listLabel(listName, id, config) {
  if (id == null || id === '') return '';
  const o = listOptions(listName, config).find((x) => x.id === String(id));
  return o ? o.label : String(id);
}

export function listValue(listName, id, config) {
  const o = listOptions(listName, config).find((x) => x.id === String(id));
  return o?.value ?? null;
}

export function entityLabel(type, config, pluralForm = false) {
  const e = ENTITIES[type];
  if (!e) return type;
  const terms = config?.settings?.terminology || {};
  return terms[`entity.${type}${pluralForm ? '.plural' : ''}`] || (pluralForm ? e.plural : e.label);
}
